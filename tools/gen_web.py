#!/usr/bin/env python3
"""web/suite.html -> src/lora_node/web_suite.h (the chalet web suite, kept in flash gzipped).

Run by PlatformIO before each build (extra_scripts in platformio.ini) and by tools/build_check.sh; the
generated header is committed too, so a build without Python still works. Edit web/suite.html, never the .h.
Preview on a PC with fake data: python3 tools/web_preview.py (reads web/suite.html).
"""
import os, sys

def main(root):
    # root: the repo. Under PlatformIO this file is exec'd by SCons (no __file__): the env gives PROJECT_DIR.
    # D84d: the page goes in flash gzipped (173 KB -> ~54 KB: a third of the send time, which blocks the chalet loop)
    # with an ETag (CRC32 of the gzip) so a reload gets a 304 and no bytes when the page has not changed.
    import gzip, zlib
    SRC = os.path.join(root, "web", "suite.html")
    DST = os.path.join(root, "src", "lora_node", "web_suite.h")
    html = open(SRC, "rb").read()
    gz = gzip.compress(html, compresslevel=9, mtime=0)   # mtime 0: the same input gives the same bytes (no spurious rebuild)
    etag = "%08x" % (zlib.crc32(gz) & 0xffffffff)
    out = ["// GENERATED by tools/gen_web.py from web/suite.html - edit the .html, not this file.",
           "#pragma once", "#include <pgmspace.h>",
           "// gzip of web/suite.html (%d bytes raw)" % len(html),
           'static const char SUITE_PAGE_ETAG[] PROGMEM = "\\"%s\\"";' % etag,
           "static const size_t SUITE_PAGE_GZ_LEN = %d;" % len(gz),
           "static const uint8_t SUITE_PAGE_GZ[] PROGMEM = {"]
    for k in range(0, len(gz), 24):
        out.append("  " + ",".join("0x%02x" % b for b in gz[k:k + 24]) + ",")
    out.append("};")
    out.append("")
    text = "\n".join(out)
    old = open(DST, encoding="utf-8").read() if os.path.exists(DST) else None
    if old != text:
        open(DST, "w", encoding="utf-8").write(text)
        print("web_suite.h: %d bytes of HTML, %d bytes gzipped, etag %s" % (len(html), len(gz), etag))

try:
    Import("env")  # noqa: F821  (PlatformIO extra_scripts entry point)
    main(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    main(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
